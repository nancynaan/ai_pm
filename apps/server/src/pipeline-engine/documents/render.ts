export interface RenderedDocument {
  type: DocumentType;
  title: string;
  /** page: the Feature Brief or a page under it; block: this feature's block on a shared page. */
  kind: 'page' | 'block';
  /** False for a roadmap proposal the feature does not need. */
  needed: boolean;
  /** For the in-app preview: macros shown as text. */
  markdown: string;
  /** Confluence storage format. */
  storage: string;
  /** Figure key → value, for every {{figure:key}} the document printed. */
  figures: Record<string, string>;
}

export type Links = TableContext['links'];

/** Page titles are unique per Confluence space, so every page carries the FA number. */
export function documentTitle(inputs: DocumentInputs, type: DocumentType): string {
  const fa = `FA-${inputs.faNumber}`;
  if (type === 'feature_brief')
    return `${fa} Feature Brief: ${inputs.featureName}${inputs.epicKey ? ` (${inputs.epicKey})` : ''}`;
  return `${fa} ${DOCUMENT_LABEL[type].replace(' (update)', '')}`;
}

/** The writer's structured text → Markdown for the {{text:x}} slots. */
export function draftTexts(draft: DocumentDraft, inputs: DocumentInputs): Record<string, string> {
  const titleOf = new Map(inputs.analysis.requirements.map((r) => [r.code, r.title]));
  const order = inputs.analysis.requirements.map((r) => r.code);
  const criteria = [...draft.requirements.acceptanceCriteria].sort(
    (a, b) => order.indexOf(a.requirementCode) - order.indexOf(b.requirementCode),
  );
  return {
    problem: draft.brief.problem,
    objectives: draft.brief.objectives,
    expected_value: draft.brief.expectedValue,
    scope: draft.brief.scope,
    impact: draft.brief.impact,
    recommendation: draft.brief.recommendation,
    user_flows: draft.requirements.userFlows
      .map(
        (flow, i) =>
          `**Flow ${i + 1}: ${flow.name}** (${flow.requirementCodes.join(', ')})\n\n${flow.steps.map((s, n) => `${n + 1}. ${s}`).join('\n')}`,
      )
      .join('\n\n'),
    business_rules: draft.requirements.businessRules.length
      ? markdownTable(draft.requirements.businessRules, [
          {
            header: 'ID',
            value: (r) => `BR-${String(draft.requirements.businessRules.indexOf(r) + 1).padStart(2, '0')}`,
          },
          { header: 'Rule', value: (r) => r.rule },
          { header: 'Requirements', value: (r) => r.requirementCodes.join(', ') },
        ])
      : '_No business rules beyond the requirements._',
    acceptance_criteria: criteria
      .map(
        (c) =>
          `**${c.requirementCode} ${titleOf.get(c.requirementCode) ?? ''}**`.trimEnd() +
          `\n\n${c.criteria.map((x) => `- ${x}`).join('\n')}`,
      )
      .join('\n\n'),
    sequencing: draft.estimation.sequencing,
    confidence: draft.estimation.confidence,
    roadmap: draft.roadmap ?? '',
  };
}

const DECISION: Record<string, { label: string; colour: 'Green' | 'Yellow' | 'Red' }> = {
  approve: { label: 'Approved', colour: 'Green' },
  decline: { label: 'Declined', colour: 'Red' },
};

interface Macro {
  storage: string;
  text: string;
}

function macros(
  inputs: DocumentInputs,
  figures: Figures,
  childTitles: string[],
  deckPublished: boolean,
): Record<string, Macro> {
  const v = inputs.assessment.verdict;
  const colour = v.decision === 'go' ? 'Green' : v.decision === 'no_go' ? 'Red' : 'Yellow';
  const notice = `Generated by the AI PM pipeline for ${figures.fa} on ${inputs.assessment.createdAt.slice(0, 10)}. Tables and figures come from the pipeline database; the text was drafted by AI. Estimates are preliminary until the development team re-estimates them in Backlog Refinement.`;
  const reasons = inputs.assessment.preliminaryReasons.join(' ');
  const clientDecision = [...inputs.decisions].reverse().find((d) => d.gate === 'assessment')?.decision;
  return {
    notice: { storage: panel('info', notice), text: `> ${notice}` },
    preliminary: inputs.assessment.preliminary
      ? {
          storage: panel('note', `Preliminary assessment. ${reasons}`),
          text: `> **Preliminary assessment.** ${reasons}`,
        }
      : { storage: '', text: '' },
    // The recommendation, and once the client has decided, the decision next to it.
    verdict: clientDecision
      ? {
          storage: `${statusMacro(colour, v.label)} ${statusMacro(DECISION[clientDecision]!.colour, `Client: ${DECISION[clientDecision]!.label}`)}`,
          text: `**${v.label}** · Client: **${DECISION[clientDecision]!.label}**`,
        }
      : { storage: statusMacro(colour, v.label), text: `**${v.label}**` },
    proposed: { storage: statusMacro('Blue', 'Proposed'), text: '**Proposed**' },
    // The child pages, then the client deck once the client has published it to this page.
    children: deckPublished
      ? {
          storage: `${childrenMacro()}<p><strong>Client presentation</strong></p>${viewFileMacro(proposalFileName(inputs.faNumber))}`,
          text: `${childTitles.map((t) => `- ${t}`).join('\n')}\n\n**Client presentation:** ${proposalFileName(inputs.faNumber)} (attached to this page)`,
        }
      : {
          storage: `${childrenMacro()}<p><strong>Client presentation:</strong> not published to Confluence.</p>`,
          text: `${childTitles.map((t) => `- ${t}`).join('\n')}\n\n**Client presentation:** not published to Confluence.`,
        },
  };
}

function fill(
  name: TemplateName,
  templates: Templates,
  slots: { texts: Record<string, string>; tables: Record<string, () => string> },
): string {
  return templates[name].replace(
    /\{\{(text|table|list):([a-z_]+)\}\}/g,
    (placeholder, kind: string, key: string) => {
      if (kind === 'text') {
        const text = slots.texts[key];
        if (text === undefined) throw new Error(`${name}: no writer text for ${placeholder}`);
        return text;
      }
      const build = slots.tables[key];
      if (!build) throw new Error(`${name}: no table for ${placeholder}`);
      return build();
    },
  );
}

/**
 * Renders all documents of a feature. `draft` is null for the shared-page blocks only (they have
 * no writer text) and in tests; links are the Confluence URLs known so far.
 */
export function renderDocuments(
  inputs: DocumentInputs,
  draft: DocumentDraft,
  templates: Templates,
  links: Links,
): RenderedDocument[] {
  const figures = buildFigures(inputs);
  const roadmapNeeded = needsRoadmapProposal(inputs.assessment.roadmapImpact);
  const childTypes: DocumentType[] = [
    'requirements',
    'estimation',
    ...(roadmapNeeded ? (['roadmap_proposal'] as const) : []),
  ];
  const allMacros = macros(
    inputs,
    figures,
    childTypes.map((t) => documentTitle(inputs, t)),
    links.deck ?? false,
  );
  const slots = { texts: draftTexts(draft, inputs), tables: tables({ inputs, figures, links }) };

  const make = (type: DocumentType, kind: RenderedDocument['kind'], needed = true): RenderedDocument => {
    const title = documentTitle(inputs, type);
    if (!needed) return { type, title, kind, needed, markdown: '', storage: '', figures: {} };
    const filled = fill(type, templates, slots);
    const used = Object.fromEntries(figureKeys(filled).map((k) => [k, figures[k] ?? '']));
    const body = fillFigures(filled, figures);
    const storageMacros = Object.fromEntries(Object.entries(allMacros).map(([k, m]) => [k, m.storage]));
    const markdown = body.replace(/\{\{macro:([a-z_]+)\}\}/g, (all, k: string) => allMacros[k]?.text ?? all);
    return {
      type,
      title,
      kind,
      needed,
      markdown,
      storage: markdownToStorage(body, storageMacros),
      figures: used,
    };
  };

  return [
    make('feature_brief', 'page'),
    make('requirements', 'page'),
    make('estimation', 'page'),
    make('risk_register', 'block'),
    make('assumption_log', 'block'),
    make('roadmap_proposal', 'page', roadmapNeeded),
  ];
}

/** The page shown when a roadmap proposal published earlier is no longer needed. */
export function withdrawnProposal(inputs: DocumentInputs): string {
  return markdownToStorage(
    `{{macro:withdrawn}}\n\nThe current assessment of ${`FA-${inputs.faNumber}`} no longer changes the roadmap, so this proposal is withdrawn. Nothing on the roadmap changes.`,
    { withdrawn: statusMacro('Grey', 'Withdrawn') },
  );
}
